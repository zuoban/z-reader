"""Preserve old Noto Serif SC glyphs absent from fontsource's Unicode subsets.

Regenerate after upgrading @fontsource/noto-serif-sc:
    python -m pip install 'fonttools[woff]'
    python scripts/generate-noto-compat.py
No Python dependency is required when building or running the application.
"""

import re
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

FRONTEND = Path(__file__).resolve().parent.parent
PACKAGE = FRONTEND / "node_modules/@fontsource/noto-serif-sc"
DESTINATION = FRONTEND / "src/app/fonts"

DESTINATION.mkdir(parents=True, exist_ok=True)
faces = ["/* Generated by scripts/generate-noto-compat.py. Font licensed under OFL-1.1. */"]

for weight in (400, 600, 700):
    source = PACKAGE / "files" / f"noto-serif-sc-chinese-simplified-{weight}-normal.woff2"
    font = TTFont(source)
    existing = set()
    for filename in re.findall(r"files/([^)]*\.woff2)", (PACKAGE / f"{weight}.css").read_text()):
        existing.update(TTFont(PACKAGE / "files" / filename).getBestCmap())
    missing = set(font.getBestCmap()) - existing
    if not missing:
        continue

    options = subset.Options()
    options.flavor = "woff2"
    subsetter = subset.Subsetter(options=options)
    subsetter.populate(unicodes=missing)
    subsetter.subset(font)
    filename = f"noto-serif-sc-compat-{weight}.woff2"
    font.save(DESTINATION / filename)
    unicode_range = ",".join(f"U+{codepoint:X}" for codepoint in sorted(missing))
    faces.append(f"""@font-face {{
  font-family: 'Noto Serif SC';
  font-style: normal;
  font-display: swap;
  font-weight: {weight};
  src: url('./{filename}') format('woff2');
  unicode-range: {unicode_range};
}}""")
    print(f"{weight}: preserved {len(missing)} codepoints in {filename}")

(DESTINATION / "noto-serif-sc-compat.css").write_text("\n\n".join(faces) + "\n")
(DESTINATION / "OFL.txt").write_text((PACKAGE / "LICENSE").read_text())
